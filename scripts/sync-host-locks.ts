#!/usr/bin/env bun
/**
 * Keep the committed npm lockfiles for the host CLIs in step with the pin
 * file `scripts/opencode-host-pins.json`.
 *
 * The v2 host contract job installs `@opencode/cli` with `npm ci` from a lock
 * under `scripts/host-locks/`, so the install is hash-pinned (OpenSSF
 * Scorecard, Pinned-Dependencies) instead of `npm install <pkg>@<version>`.
 * The pin file stays the one home of the version. Renovate bumps it through a
 * regex manager and runs `bun run postupgrade`, which runs `surfaces:regen`
 * and so this script (the `host-locks` generated surface), so a bump lands the
 * regenerated lock in the same PR. `surfaces:drift` runs `--check` in CI.
 *
 * Usage:
 *   bun scripts/sync-host-locks.ts          # Write each manifest, refresh a stale lock (needs network)
 *   bun scripts/sync-host-locks.ts --check  # Report disagreement; offline, exit 1 on any problem
 *
 * Nothing runs on import. The executable entrypoint is guarded with
 * `if (import.meta.main)`.
 */

import { spawnSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import {
  OPENCODE_CLI_PACKAGES,
  type OpencodeHost,
  readOpencodeHostPins,
} from './lib/opencode-pin.js'

export interface HostLock {
  /** The pin file key whose version the lock must hold. */
  readonly pinKey: OpencodeHost
  /** The npm package the lock installs. */
  readonly packageName: string
  /** The lock directory, relative to the repository root. */
  readonly dir: string
  /**
   * Platform binary packages the CI runners execute. The workflow runs
   * `npm ci --ignore-scripts` and then the binary from one of these, so the
   * lock must carry each with an integrity hash; a lock without one would
   * leave the install with no binary. Same version as the CLI.
   */
  readonly platformPackages: readonly string[]
}

/**
 * One lock per host CLI that a workflow installs through npm. The v1 CLI jobs
 * launch through `bunx` and the v2 floor is not installed in CI, so neither
 * has a lock. A test pins this list against the workflow.
 */
export const HOST_LOCKS: readonly HostLock[] = [
  {
    pinKey: 'v2',
    packageName: OPENCODE_CLI_PACKAGES.v2,
    dir: 'scripts/host-locks/opencode-v2',
    // Every host-contract job runs on ubuntu-latest, an x64 runner. A test pins
    // the runner and the step's platform mapping to this entry.
    platformPackages: ['@opencode/cli-linux-x64'],
  },
]

const REPO_ROOT = path.resolve(import.meta.dir, '..')

const MANIFEST_FILE = 'package.json'
const LOCK_FILE = 'package-lock.json'
const REGISTRY_PREFIX = 'https://registry.npmjs.org/'

type JsonObject = Record<string, unknown>

function isJsonObject(value: unknown): value is JsonObject {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

function readJsonObject(file: string): JsonObject | string {
  if (!fs.existsSync(file)) return `${path.basename(file)} is missing`
  try {
    const parsed: unknown = JSON.parse(fs.readFileSync(file, 'utf8'))
    return isJsonObject(parsed)
      ? parsed
      : `${path.basename(file)} is not a JSON object`
  } catch (error) {
    return `${path.basename(file)} is not valid JSON: ${
      error instanceof Error ? error.message : String(error)
    }`
  }
}

/** The manifest a lock directory must hold for `lock` at `version`. */
export function renderManifest(lock: HostLock, version: string): string {
  const manifest = {
    name: `systematic-host-lock-${lock.pinKey}`,
    private: true,
    description: `Lockfile source for the ${lock.packageName} package used by the host contract jobs. Generated by scripts/sync-host-locks.ts from scripts/opencode-host-pins.json; do not edit.`,
    dependencies: { [lock.packageName]: version },
  }
  return `${JSON.stringify(manifest, null, 2)}\n`
}

/** `sha512-` plus base64 that decodes to exactly 64 bytes, canonically encoded. */
function isSha512Integrity(value: unknown): boolean {
  if (typeof value !== 'string') return false
  const match = /^sha512-([A-Za-z0-9+/]{86}==)$/.exec(value)
  const encoded = match?.[1]
  if (encoded === undefined) return false
  const decoded = Buffer.from(encoded, 'base64')
  return decoded.length === 64 && decoded.toString('base64') === encoded
}

/** What is wrong with one locked package entry, or `[]`. */
function entryProblems(
  where: string,
  key: string,
  entry: unknown,
  expectedVersion: string | undefined,
): string[] {
  if (!isJsonObject(entry)) return [`${where}: ${key} is not an object`]
  const problems: string[] = []
  if (typeof entry.version !== 'string' || entry.version === '') {
    problems.push(`${where}: ${key} has no version`)
  } else if (
    expectedVersion !== undefined &&
    entry.version !== expectedVersion
  ) {
    problems.push(`${where}: ${key} must resolve to ${expectedVersion}`)
  }
  if (
    typeof entry.resolved !== 'string' ||
    !entry.resolved.startsWith(REGISTRY_PREFIX)
  ) {
    problems.push(`${where}: ${key} does not resolve to ${REGISTRY_PREFIX}`)
  }
  if (!isSha512Integrity(entry.integrity)) {
    problems.push(
      `${where}: ${key} has no valid sha512 integrity hash (64 bytes of base64 after "sha512-")`,
    )
  }
  return problems
}

function lockProblems(lock: HostLock, version: string, content: JsonObject) {
  const problems: string[] = []
  const where = `${lock.dir}/${LOCK_FILE}`

  if (
    typeof content.lockfileVersion !== 'number' ||
    content.lockfileVersion < 3
  ) {
    problems.push(`${where}: lockfileVersion must be 3 or later`)
  }
  const packages = content.packages
  if (!isJsonObject(packages)) {
    problems.push(`${where}: has no "packages" map`)
    return problems
  }

  const root = packages['']
  const rootDeps = isJsonObject(root) ? root.dependencies : undefined
  if (
    !isJsonObject(rootDeps) ||
    JSON.stringify(rootDeps) !== JSON.stringify({ [lock.packageName]: version })
  ) {
    problems.push(
      `${where}: the root dependencies must be exactly ${lock.packageName}@${version}`,
    )
  }

  // The CLI and its runner platform packages must be present at the pin; every
  // other entry only has to be well formed.
  const required = new Set(
    [lock.packageName, ...lock.platformPackages].map(
      (name) => `node_modules/${name}`,
    ),
  )
  for (const key of required) {
    if (!(key in packages)) {
      problems.push(
        `${where}: ${key} is missing; the install would have no binary to run`,
      )
    }
  }
  for (const [key, entry] of Object.entries(packages)) {
    if (key === '') continue
    problems.push(
      ...entryProblems(
        where,
        key,
        entry,
        required.has(key) ? version : undefined,
      ),
    )
  }
  return problems
}

/**
 * The ways a lock directory disagrees with `version`, or `[]` when it agrees.
 * Reads only; never touches the network. Checks that the manifest names the
 * CLI at exactly the pin, that the lock resolves that version, and that every
 * locked package has a sha512 integrity hash and a registry URL.
 */
export function findLockProblems(
  rootDir: string,
  lock: HostLock,
  version: string,
): string[] {
  const dir = path.join(rootDir, lock.dir)
  const problems: string[] = []

  const manifestPath = path.join(dir, MANIFEST_FILE)
  if (!fs.existsSync(manifestPath)) {
    problems.push(`${lock.dir}/${MANIFEST_FILE} is missing`)
  } else if (
    fs.readFileSync(manifestPath, 'utf8') !== renderManifest(lock, version)
  ) {
    problems.push(
      `${lock.dir}/${MANIFEST_FILE} does not declare ${lock.packageName}@${version}`,
    )
  }

  const content = readJsonObject(path.join(dir, LOCK_FILE))
  if (typeof content === 'string') {
    problems.push(`${lock.dir}/${content}`)
  } else {
    problems.push(...lockProblems(lock, version, content))
  }
  return problems
}

/**
 * Refreshes the manifest and lock for `version` when they disagree with it. A
 * lock that already agrees is left alone, so a second run is a no-op and needs
 * no network.
 *
 * The lock is built in a scratch directory and checked there, and only a
 * result that passes every check replaces the committed files. A failed or
 * incomplete npm run therefore never leaves a half-written lock behind. The
 * scratch run starts with no lock, so a stale or malformed one cannot carry
 * old resolutions forward; every package in this tree is pinned exactly.
 * `--ignore-scripts` only skips the CLI's postinstall here, which resolving
 * metadata never needed.
 */
export function syncHostLock(
  rootDir: string,
  lock: HostLock,
  version: string,
): void {
  if (findLockProblems(rootDir, lock, version).length === 0) return

  // `realpath`: npm records a lock's paths relative to the link target when
  // given a symlinked directory (macOS /tmp), and writes a lock `npm ci` rejects.
  const staging = fs.realpathSync(
    fs.mkdtempSync(path.join(os.tmpdir(), 'host-lock-')),
  )
  try {
    const work = path.join(staging, lock.dir)
    fs.mkdirSync(work, { recursive: true })
    fs.writeFileSync(
      path.join(work, MANIFEST_FILE),
      renderManifest(lock, version),
    )

    const result = spawnSync(
      'npm',
      [
        'install',
        '--package-lock-only',
        '--ignore-scripts',
        '--no-audit',
        '--no-fund',
      ],
      { cwd: work, stdio: 'inherit' },
    )
    if (result.status !== 0) {
      throw new Error(
        `npm failed to refresh ${lock.dir}/${LOCK_FILE}; nothing was written`,
      )
    }
    const problems = findLockProblems(staging, lock, version)
    if (problems.length > 0) {
      throw new Error(
        `npm produced a lock that fails its checks; nothing was written:\n${problems.join('\n')}`,
      )
    }

    const target = path.join(rootDir, lock.dir)
    fs.mkdirSync(target, { recursive: true })
    for (const file of [MANIFEST_FILE, LOCK_FILE]) {
      const partial = path.join(target, `.${file}.tmp`)
      fs.copyFileSync(path.join(work, file), partial)
      fs.renameSync(partial, path.join(target, file))
    }
  } finally {
    fs.rmSync(staging, { recursive: true, force: true })
  }
}

function main(argv: readonly string[]): number {
  const pins = readOpencodeHostPins()
  if (argv.includes('--check')) {
    const problems = HOST_LOCKS.flatMap((lock) =>
      findLockProblems(REPO_ROOT, lock, pins[lock.pinKey]),
    )
    for (const problem of problems) console.error(`[FAIL] ${problem}`)
    if (problems.length > 0) {
      console.error('Run `bun run host-locks:sync` to regenerate the locks.')
      return 1
    }
    console.log(`host locks agree with the pin file (${HOST_LOCKS.length})`)
    return 0
  }
  for (const lock of HOST_LOCKS) {
    syncHostLock(REPO_ROOT, lock, pins[lock.pinKey])
    console.log(
      `synced ${lock.dir} to ${lock.packageName}@${pins[lock.pinKey]}`,
    )
  }
  return 0
}

if (import.meta.main) {
  process.exit(main(process.argv.slice(2)))
}
